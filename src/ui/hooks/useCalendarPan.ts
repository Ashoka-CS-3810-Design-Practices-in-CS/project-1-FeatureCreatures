import { useEffect, type RefObject } from 'react';
import { CALENDAR_PAN_THRESHOLD_PX } from '@/shared/constants';

interface PanStart {
  pointerId: number;
  clientX: number;
  clientY: number;
  scrollLeft: number;
  scrollTop: number;
  scroller: HTMLElement;
}

// PRE:  rootRef receives the calendar's DOM container; locked is the session gesture lock
// POST: while locked, dragging the time grid pans its scroller and suppresses the resulting click;
//       a click without dragging still opens an event; listeners and pointer capture are cleaned up
export function useCalendarPan(rootRef: RefObject<HTMLDivElement | null>, locked: boolean): void {
  useEffect(() => {
    const root = rootRef.current;
    if (root === null || !locked) return;
    let start: PanStart | null = null;
    let moved = false;
    root.classList.add('is-locked');

    // PRE:  event is a pointerdown inside the calendar
    // POST: records a primary pointer's time-grid scroller without consuming an ordinary event click
    function begin(event: PointerEvent): void {
      moved = false;
      const target = event.target;
      if (
        event.button !== 0 ||
        !(target instanceof Element) ||
        target.closest('.fc-timegrid-body') === null
      )
        return;
      const scroller = target.closest<HTMLElement>('.fc-scroller');
      if (scroller === null) return;
      start = {
        pointerId: event.pointerId,
        clientX: event.clientX,
        clientY: event.clientY,
        scrollLeft: scroller.scrollLeft,
        scrollTop: scroller.scrollTop,
        scroller,
      };
    }

    // PRE:  event is a pointermove inside the calendar or captured by its scroller
    // POST: after the drag threshold, scrolls by displacement from the initial pointer and captures it
    function move(event: PointerEvent): void {
      if (start === null || event.pointerId !== start.pointerId) return;
      const horizontal = event.clientX - start.clientX;
      const vertical = event.clientY - start.clientY;
      if (!moved && Math.hypot(horizontal, vertical) < CALENDAR_PAN_THRESHOLD_PX) return;
      if (!moved) start.scroller.setPointerCapture(event.pointerId);
      moved = true;
      event.preventDefault();
      root?.classList.add('is-panning');
      start.scroller.scrollLeft = start.scrollLeft - horizontal;
      start.scroller.scrollTop = start.scrollTop - vertical;
    }

    // PRE:  a pointer ended or the hook is being cleaned up
    // POST: releases any captured pointer and clears the active drag, preserving click suppression
    function finish(): void {
      if (start?.scroller.hasPointerCapture(start.pointerId))
        start.scroller.releasePointerCapture(start.pointerId);
      start = null;
      root?.classList.remove('is-panning');
    }

    // PRE:  event is a captured click inside the calendar
    // POST: consumes the click generated by a completed pan, leaving ordinary clicks untouched
    function click(event: MouseEvent): void {
      if (!moved) return;
      moved = false;
      event.preventDefault();
      event.stopImmediatePropagation();
    }

    root.addEventListener('pointerdown', begin);
    root.addEventListener('pointermove', move);
    root.addEventListener('pointerup', finish);
    root.addEventListener('pointercancel', finish);
    root.addEventListener('click', click, true);
    return () => {
      finish();
      root.classList.remove('is-locked');
      root.removeEventListener('pointerdown', begin);
      root.removeEventListener('pointermove', move);
      root.removeEventListener('pointerup', finish);
      root.removeEventListener('pointercancel', finish);
      root.removeEventListener('click', click, true);
    };
  }, [rootRef, locked]);
}
